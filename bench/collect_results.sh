# Regenerate docs/RESULTS.md from the saved outputs in docs/results/.
# Runs the host tests (any C compiler) to save their output too; everything
# else comes from files written by make test, make test-pc,
# bench/measure.sh, bench/recovery.sh and tests/third_party/fetch_and_run.sh.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
R="$ROOT/docs/results"
make -s -C "$ROOT/tests/host" clean >/dev/null 2>&1 || true
make -s -C "$ROOT/tests/host" > "$R/host-tests.txt" 2>&1 || true

python3 - "$R" > "$ROOT/docs/RESULTS.md" <<'EOF'
import os, re, sys
R = sys.argv[1]

def read(name):
    p = os.path.join(R, name)
    return open(p).read() if os.path.exists(p) else ""

def result(text):
    m = re.search(r"RESULT (.*)", text)
    return dict(kv.split("=") for kv in m.group(1).split()) if m else {}

out = []
w = out.append
w("# Results\n")
w("Generated by `bench/collect_results.sh` from the files in `docs/results/`. "
  "Every number below comes from one of those files, named in each section. "
  "All on-target times are measured inside QEMU (KVM under WSL2): they are emulated, see `docs/LIMITS.md`.\n")

w("## Tests\n")
w("| Suite | Result | File |\n|---|---|---|")
host = re.search(r"(\d+) cases, (\d+) failed, (\d+) checks", read("host-tests.txt"))
if host:
    w(f"| host tests, `driver/core` against a software controller model | {host.group(1)} cases, {host.group(2)} failed, {host.group(3)} checks | host-tests.txt |")
for name, label in (("tests-q35.txt", "on-target, QEMU q35 (ICH9)"), ("tests-pc.txt", "on-target, QEMU pc (PIIX4)")):
    m = re.search(r"(\d+) cases, (\d+) passed, (\d+) failed", read(name))
    if m:
        w(f"| {label} | {m.group(2)} of {m.group(1)} passed | {name} |")
s = read("qnx-sample.txt")
if s:
    n = s.count("\nPASS")
    w(f"| QNX's own I2C sample library (hardware-component-samples) | {n} of {n + s.count(chr(10) + 'FAIL')} checks passed | qnx-sample.txt |")
w("")

w("## Polling and interrupt mode\n")
w("10,000 two-byte reads, then 2,000 32-byte block reads, from `tests-q35.txt`. "
  "Why these mostly measure QEMU is in `docs/DESIGN.md` (What the timing numbers mean).\n")
t = read("tests-q35.txt")
rows = re.findall(r"PASS  soak (\w+): (\d+) (?:x )?([\w -]+?)\s+\[\w+\]\n\s+OK n=\d+ us=(\d+)(?:\n\s+\d+ \S+\s+\d+ \w+ \d+ [\d:]+\s+([\d.]+))?", t)
if rows:
    w("| Mode | Transfer | Time per transfer | Driver CPU (word-read run) |\n|---|---|---|---|")
    for mode, n, what, us, cpu in rows:
        w(f"| {'polling' if mode == 'poll' else 'interrupt'} | {what.strip()} | {us} µs | {cpu + ' s' if cpu else ''} |")
w("")

w("## thermd: deadlines under load\n")
w("thermd samples both sensors every 10 ms at SCHED_FIFO priority; the deadline is the period. "
  "`hog` spins on every processor at priority 20. From the host, sensor 0x48 jumps to 91 C a third of the way through each run "
  "and back to 40 C at two thirds. Wake-up lateness and response time are measured from the start of each period, in microseconds.\n")
w("| Run | thermd priority | Periods | Missed | No wake-up | Lateness p99 / max | Response p99 / max | Fan on after | File |")
w("|---|---|---|---|---|---|---|---|---|")
runs = [("baseline", "no load, interrupt mode"), ("hog-irq", "hog at 20, interrupt mode"),
        ("hog-poll", "hog at 20, polling mode"), ("hog-low", "hog at 20, thermd below it"),
        ("host-load", "no load in QNX, two busy loops on the host"),
        ("inversion-before-fix", "hog at 20, driver before the priority fix (20 s run)")]
for name, label in runs:
    text = read(f"thermd-{name}.txt")
    r = result(text)
    if not r:
        continue
    fan = re.search(r"fan ON , (\d+) us", text[:re.search(r"RESULT ", text).start()])
    w(f"| {label} | {r['prio']} | {r['periods']} | {r['missed']} | {r['skipped']} | "
      f"{r['late_p99_us']} / {r['late_max_us']} | {r['resp_p99_us']} / {r['resp_max_us']} | "
      f"{fan.group(1) + ' µs' if fan else 'never'} | thermd-{name}.txt |")
w("")
w("What to read from this: below hog, thermd loses every period while hog runs and never sees the over-temperature; "
  "above it, it loses almost none. The few misses at priority 30 have wake-up lateness spikes of several milliseconds "
  "with nothing of higher priority running in QNX. The host-load run gets misses of the same kind with no load in QNX at all, "
  "only with the host busy, so they most likely come from the emulated processors not getting host time, which no priority "
  "inside the guest can fix. The host-load run has no temperature change if it was recorded before `measure.sh` included it.\n")

rec = read("recovery.txt")
if rec:
    w("## Recovery from a killed driver\n")
    w("`kill -9` of the driver every 2 s under `smb-supervisor`, with `thermd` running, from `recovery.txt`.\n")
    kills = re.search(r"recovery: (\d+) x kill", rec)
    restarts = [int(x) for x in re.findall(r"serving again, (\d+) ms", rec)]
    gaps = re.search(r"ms without data:([\d ]+)\)", rec)
    gaps = [int(x) for x in gaps.group(1).split()] if gaps else []
    r = result(rec)
    def mmm(v):
        v = sorted(v)
        return f"{v[0]} / {v[len(v) // 2]} / {v[-1]} ms" if v else "-"
    w("| Kills | Restarts | Restart time min / median / max | thermd gaps | Gap without data min / median / max | thermd missed deadlines |")
    w("|---|---|---|---|---|---|")
    w(f"| {kills.group(1) if kills else '?'} | {len(restarts)} | {mmm(restarts)} | {r.get('gaps', '?')} | {mmm(gaps)} | {r.get('missed', '?')} |")
    w("")
    w("Restart time is from the supervisor's death notice (a `_PULSE_CODE_COIDDEATH` pulse) to `/dev/i2c0` open again. "
      "The gap is from thermd's last good sample before the kill to its first good one after, so it includes up to one 10 ms period of waiting.\n")

print("\n".join(out))
EOF
echo "wrote docs/RESULTS.md"
